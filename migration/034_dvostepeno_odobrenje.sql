-- ============================================================================
-- Migration 034: двостепено одобрење радне листе (шеф одељења + директор)
-- ============================================================================
-- Date: July 2026
-- Радна листа запосленог се сматра ОДОБРЕНОМ тек кад је потврде И шеф одељења
-- И директор — оба потписа су обавезна. До тада статус остаје SUBMITTED
-- (делимично потврђено). Враћање на допуну (REJECTED) поништава ОБА потписа и
-- циклус креће испочетка.
--
-- Ове колоне бележе појединачне потписе (ко и када). Постојеће
-- is_verified/verified_by/verified_at остају и попуњавају се тек кад је листа
-- ПОТПУНО одобрена (компатибилно са старим читачима).
--
-- Изузеци (постојеће понашање, не измишљено ново правило):
--   * одељење БЕЗ шефа (нпр. Едукација/Галерија/Директор) → потребан је само
--     потпис директора (head слот се не тражи);
--   * листа самог шефа одељења → потписује је директор (нема шефа изнад);
--   * иста особа је и шеф и директор → њен један потпис попуњава оба слота
--     (особа не може да потписује два пута).
-- Архивски увоз (imported_from='word-arhiva') остаје већ одобрен, без потписа.
-- ============================================================================

ALTER TABLE timesheet_reports
    ADD COLUMN IF NOT EXISTS head_verified_by VARCHAR(255),
    ADD COLUMN IF NOT EXISTS head_verified_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS director_verified_by VARCHAR(255),
    ADD COLUMN IF NOT EXISTS director_verified_at TIMESTAMPTZ;

COMMENT ON COLUMN timesheet_reports.head_verified_by IS
    'Email шефа одељења који је потврдио листу (први потпис); NULL = још није';
COMMENT ON COLUMN timesheet_reports.director_verified_by IS
    'Email директора који је потврдио листу (други потпис); NULL = још није';
