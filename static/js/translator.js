    function transliterateCyrLat(text, toCyrillic) {
        if (toCyrillic) {
            let result = text;
            for (const [lat, cyr] of Object.entries(digraphs)) {
                result = result.split(lat).join(cyr);
            }
            for (const [lat, cyr] of Object.entries(latToCyr)) {
                result = result.split(lat).join(cyr);
            }
            return result;
        } else {
            const chars = Array.from(text);
            let result = '';
            for (let i = 0; i < chars.length; i++) {
                const ch = chars[i];
                if (upperDigraph[ch]) {
                    // Uppercase Љ/Њ/Џ: emit all-caps (NJ) inside an all-caps
                    // word, title-case (Nj) otherwise. Decide from the nearest
                    // Serbian letter — look ahead first, then behind.
                    let ctx = null;
                    for (let j = i + 1; j < chars.length; j++) {
                        if (isCyrLetter(chars[j])) { ctx = isUpperCyrLetter(chars[j]); break; }
                    }
                    if (ctx === null) {
                        for (let j = i - 1; j >= 0; j--) {
                            if (isCyrLetter(chars[j])) { ctx = isUpperCyrLetter(chars[j]); break; }
                        }
                    }
                    result += ctx ? upperDigraph[ch] : cyrToLat[ch];
                } else {
                    result += cyrToLat[ch] || ch;
                }
            }
            return result;
        }
    }

    // Any Latin or Cyrillic letter — a match must not sit flush against one
    // when the key's own edge is a letter, so short keys (од, Да, Пол, Пон…)
    // never chew through the middle of an unrelated word.
    const LETTER_RE = /[A-Za-zČĆŽŠĐčćžšđЀ-ӿ]/;
    function isLetter(ch) {
        return ch !== '' && LETTER_RE.test(ch);
    }

    // Replace every whole-word occurrence of `key` with `val`. A boundary is
    // required only on a key edge that is itself a letter (keys ending in ':',
    // '*', ')' etc. keep matching regardless of what follows).
    function replaceWholeWord(text, key, val) {
        const needBefore = isLetter(key[0]);
        const needAfter = isLetter(key[key.length - 1]);
        let out = '';
        let from = 0;
        let idx;
        while ((idx = text.indexOf(key, from)) !== -1) {
            const before = idx > 0 ? text[idx - 1] : '';
            const after = idx + key.length < text.length ? text[idx + key.length] : '';
            if ((!needBefore || !isLetter(before)) && (!needAfter || !isLetter(after))) {
                out += text.slice(from, idx) + val;
                from = idx + key.length;
            } else {
                out += text.slice(from, idx + 1);
                from = idx + 1;
            }
        }
        return out + text.slice(from);
    }

    function translateToEnglish(text) {
        let result = text;
        for (let i = 0; i < sortedKeys.length; i++) {
            const key = sortedKeys[i];
            if (result.indexOf(key) !== -1) {
                result = replaceWholeWord(result, key, enTranslations[key]);
            }
        }
        return result;
    }

    function getTextNodes(root) {
        const nodes = [];
        const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
            acceptNode: function(node) {
                const p = node.parentElement;
                if (!p) return NodeFilter.FILTER_REJECT;
                if (['SCRIPT','STYLE','TEXTAREA','CODE','PRE','NOSCRIPT'].includes(p.tagName))
                    return NodeFilter.FILTER_REJECT;
                if (p.closest('[data-no-translate]'))
                    return NodeFilter.FILTER_REJECT;
                if (!node.textContent.trim()) return NodeFilter.FILTER_REJECT;
                return NodeFilter.FILTER_ACCEPT;
            }
        });
        while (walker.nextNode()) nodes.push(walker.currentNode);
        return nodes;
    }

    function applyToTextNodes(root, fn) {
        var nodes = getTextNodes(root);
        for (var i = 0; i < nodes.length; i++) {
            var node = nodes[i];
            var nv = fn(node.textContent);
            if (nv !== node.textContent) node.textContent = nv;
        }
    }

    function applyToAttributes(root, fn) {
        var attrs = ['title', 'placeholder', 'alt', 'aria-label'];
        var elems = root.querySelectorAll('*');
        for (var i = 0; i < elems.length; i++) {
            var el = elems[i];
            if (el.closest('[data-no-translate]')) continue;
            for (var j = 0; j < attrs.length; j++) {
                var a = attrs[j];
                if (el.hasAttribute(a)) {
                    var v = el.getAttribute(a);
                    var nv = fn(v);
                    if (nv !== v) el.setAttribute(a, nv);
                }
            }
        }
    }

    // Store all original Cyrillic text for reverting from English
    function storeOriginals(root) {
        var nodes = getTextNodes(root);
        for (var i = 0; i < nodes.length; i++) {
            if (!originals.has(nodes[i])) {
                originals.set(nodes[i], nodes[i].textContent);
            }
        }
        var attrs = ['title', 'placeholder', 'alt', 'aria-label'];
        var elems = root.querySelectorAll('*');
        for (var i = 0; i < elems.length; i++) {
            var el = elems[i];
            if (!originals.has(el)) {
                var saved = {};
                for (var j = 0; j < attrs.length; j++) {
                    if (el.hasAttribute(attrs[j])) {
                        saved[attrs[j]] = el.getAttribute(attrs[j]);
                    }
                }
                if (Object.keys(saved).length > 0) originals.set(el, saved);
            }
        }
    }

    function restoreOriginals(root) {
        var nodes = getTextNodes(root);
        for (var i = 0; i < nodes.length; i++) {
            var orig = originals.get(nodes[i]);
            if (orig !== undefined) nodes[i].textContent = orig;
        }
        var attrs = ['title', 'placeholder', 'alt', 'aria-label'];
        var elems = root.querySelectorAll('*');
        for (var i = 0; i < elems.length; i++) {
            var saved = originals.get(elems[i]);
            if (saved) {
                for (var a in saved) {
                    elems[i].setAttribute(a, saved[a]);
                }
            }
        }
    }

